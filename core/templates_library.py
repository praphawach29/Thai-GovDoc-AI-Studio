"""
templates_library.py — คลังแบบฟอร์มหนังสือราชการมาตรฐานสำเร็จรูป (Preset Template Library)
รวบรวมแม่แบบหนังสือราชการตามระเบียบงานสารบรรณ พ.ศ. ๒๕๒๖ ที่ใช้บ่อยในหน่วยงานภาครัฐ
พร้อมแทรก Smart Placeholders สำหรับการปรับแต่งอย่างรวดเร็ว
"""

from typing import Dict, List, Optional
from core.models import GovDocumentSchema, DocType, UrgencyLevel, SecretLevel, MemoHierarchyLevel


class PresetTemplate:
    def __init__(self, template_id: str, title: str, category: str, doc_type: DocType, schema: GovDocumentSchema):
        self.template_id = template_id
        self.title = title
        self.category = category
        self.doc_type = doc_type
        self.schema = schema


# รายการแบบฟอร์มมาตรฐาน
PRESET_TEMPLATES: Dict[str, PresetTemplate] = {}


def _register_template(t_id: str, title: str, category: str, doc_type: DocType, doc: GovDocumentSchema):
    PRESET_TEMPLATES[t_id] = PresetTemplate(t_id, title, category, doc_type, doc)


